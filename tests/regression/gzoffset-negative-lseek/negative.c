int main(void) {
    char buf[16];
    setvbuf(stdout, NULL, _IONBF, 0);
    int fd = open("/proc/self/mem", O_RDONLY);
    if (fd < 0) { perror("open /proc/self/mem"); return 2; }
    off_t at = lseek(fd, (off_t)(uintptr_t)area, SEEK_SET);
    printf("lseek to the array = %s\n", at == (off_t)(uintptr_t)area ? "the array address" : "FAILED");
    gzFile f = gzdopen(fd, "r");
    if (f == NULL) return 2;
    int n = gzread(f, buf, 10);
    printf("gzread 10 = %d, gzdirect = %d, gzoffset64 - array address = %lld (the compressed bytes consumed)\n",
           n, gzdirect(f), (long long)(gzoffset64(f) - (off_t)(uintptr_t)area));
    off_t neg = lseek(fd, INT64_MIN + 1, SEEK_SET);
    printf("lseek(fd, INT64_MIN + 1, SEEK_SET) = %lld\n", (long long)neg);
    long long o = (long long)gzoffset64(f);
    printf("gzoffset64 = %lld\n", o);
    gzclose(f);
    return 0;
}
