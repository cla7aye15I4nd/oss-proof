/* eff308a with 1eb7682: a gzip extra field longer than the caller's buffer, over two inflate calls
 * (CVE-2022-37434).
 * The gzip stream has an extra field of 100 bytes; the caller gives inflateGetHeader an extra buffer
 * of 10 bytes (extra_max 10). The first inflate call gets the header and 30 bytes of the field, and
 * stores the first 10. The second call gets the rest: the field offset len is 30, above extra_max.
 * Before the fix the copy length extra_max - len wraps, and the copy writes far past the buffer.
 * eff308a added the check len < extra_max; 1eb7682 repaired a NULL dereference that eff308a
 * introduced. Reverting both gives the code before the fix. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "zlib.h"

int main(void) {
    static const unsigned char gz[] = {
        0x1f, 0x8b, 0x08, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0x64, 0x00,
        0x03, 0x0a, 0x11, 0x18, 0x1f, 0x26, 0x2d, 0x34, 0x3b, 0x42, 0x49, 0x50,
        0x57, 0x5e, 0x65, 0x6c, 0x73, 0x7a, 0x81, 0x88, 0x8f, 0x96, 0x9d, 0xa4,
        0xab, 0xb2, 0xb9, 0xc0, 0xc7, 0xce, 0xd5, 0xdc, 0xe3, 0xea, 0xf1, 0xf8,
        0xff, 0x06, 0x0d, 0x14, 0x1b, 0x22, 0x29, 0x30, 0x37, 0x3e, 0x45, 0x4c,
        0x53, 0x5a, 0x61, 0x68, 0x6f, 0x76, 0x7d, 0x84, 0x8b, 0x92, 0x99, 0xa0,
        0xa7, 0xae, 0xb5, 0xbc, 0xc3, 0xca, 0xd1, 0xd8, 0xdf, 0xe6, 0xed, 0xf4,
        0xfb, 0x02, 0x09, 0x10, 0x17, 0x1e, 0x25, 0x2c, 0x33, 0x3a, 0x41, 0x48,
        0x4f, 0x56, 0x5d, 0x64, 0x6b, 0x72, 0x79, 0x80, 0x87, 0x8e, 0x95, 0x9c,
        0xa3, 0xaa, 0xb1, 0xb8, 0xcb, 0x48, 0xcd, 0xc9, 0xc9, 0x57, 0x48, 0xaf,
        0xca, 0x2c, 0x50, 0x48, 0xad, 0x28, 0x29, 0x4a, 0x54, 0x48, 0xcb, 0x4c,
        0xcd, 0x49, 0x51, 0xc8, 0xa0, 0x86, 0x30, 0x00, 0x75, 0x8e, 0x9c, 0xa6,
        0x5c, 0x00, 0x00, 0x00};
    unsigned char out[200], *extra = malloc(10);
    z_stream s;
    gz_header head;
    memset(&s, 0, sizeof s);
    memset(&head, 0, sizeof head);
    memset(extra, 0, 10);
    head.extra = extra; head.extra_max = 10;
    int rc = inflateInit2(&s, 31);
    int hd = inflateGetHeader(&s, &head);
    s.next_out = out; s.avail_out = sizeof out;
    s.next_in = (unsigned char *)gz; s.avail_in = 42;
    int r1 = inflate(&s, Z_NO_FLUSH);
    s.avail_in = sizeof gz - 42;
    int r2 = inflate(&s, Z_NO_FLUSH);
    int ok = r2 == Z_STREAM_END && s.total_out == 92 && head.done == 1 && head.extra_len == 100 &&
             memcmp(extra, gz + 12, 10) == 0;
    printf("init=%d header=%d inflate=%d,%d out=%lu extra_len=%u output %s\n", rc, hd, r1, r2,
           s.total_out, head.extra_len, ok ? "ok" : "WRONG");
    inflateEnd(&s);
    free(extra);
    return ok ? 0 : 1;
}
