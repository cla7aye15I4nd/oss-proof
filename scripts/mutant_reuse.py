def row_fields(line: str) -> list[str]:
    return line.split("\t")


def row_kind(line: str) -> str:
    fields = row_fields(line)
    return "row-same" if len(fields) > 5 and fields[5].startswith("same:") else "row"


def proof_roots(modules: str) -> list[str]:
    roots = []
    for module in modules.split(","):
        if not module or any(not part for part in module.split("/")):
            raise Unkeyable(f"bad proof module list: {modules!r}")
        roots.append("ZlibF/Proof/" + module + ".lean")
    return roots


def copy_workspace(root: Path, destination: Path) -> None:
    """The copy tests/audit/proofmut.sh gives a mutator: the workspace without .git, .lake,
    tests/build and zlib."""
    root = Path(root).resolve()

    def ignore(directory, names):
        skipped = {name for name in names if name in (".git", ".lake", "zlib")}
        if Path(directory).resolve() == root / "tests":
            skipped |= {"build"} & set(names)
        return skipped

    shutil.copytree(root, destination, ignore=ignore, symlinks=True)


def run_mutator(root: Path, script: str, name: str, destination: Path) -> None:
    """Apply a `script:` row to a fresh copy, exactly as the list runner does."""
    mutator = Path(root) / script
    if mutator.is_symlink() or not mutator.is_file():
        raise Unkeyable(f"missing mutator: {script}")
    copy_workspace(root, destination)
    try:
        result = subprocess.run([sys.executable, "-I", str(mutator), str(destination), name],
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=300)
    except subprocess.TimeoutExpired:
        raise Unkeyable(f"mutator timed out: {script} {name}")
    if result.returncode != 0:
        raise Unkeyable(f"mutator failed: {script} {name}")


def row_key(tree: Tree, base: str, list_path: str, line: str) -> str:
    """The key of one row of a mutant list.

    It covers: the base; the list's path and the whole row; the import closure of the row's proof
    modules in the unmutated tree (the baseline build) and in the mutated tree (the mutant build),
    each file by content; for a text row the file's text before and after the edit; for a `script:`
    row the mutator's bytes, and the mutated tree is the one the mutator leaves in a fresh copy of
    the workspace, whose build configuration is hashed again.
    """
    fields = row_fields(line)
    if not 5 <= len(fields) <= 6 or not fields[0] or not fields[1]:
        raise Unkeyable(f"malformed row: {line!r}")
    flag = fields[5] if len(fields) == 6 else ""
    if flag and not flag.startswith("same:"):
        raise Unkeyable(f"a flagged row is never reused: {fields[0]}")
    roots = proof_roots(fields[4])
    parts = ["row", base, list_path, line, closure_digest(tree, roots)]
    if fields[1].startswith("script:"):
        script = fields[1][len("script:"):]
        mutator = tree.read(script)
        if mutator is None:
            raise Unkeyable(f"missing mutator: {script}")
        with tempfile.TemporaryDirectory(prefix="mutant-key-") as directory:
            copy = Path(directory) / "w"
            run_mutator(tree.root, script, fields[0], copy)
            mutated = Tree(copy)
            if mutated.has_sorry():
                raise Unkeyable(f"the mutated copy contains sorry: {fields[0]}")
            parts += ["script", script, mutator, closure_digest(mutated, roots)]
            for path in CONFIG:
                data = mutated.read(path)
                parts += [path, "absent" if data is None else hashlib.sha256(data).hexdigest()]
    else:
        before = tree.read(fields[1])
        if before is None:
            raise Unkeyable(f"no such file: {fields[1]}")
        old, new = fields[2].replace("\\n", "\n"), fields[3].replace("\\n", "\n")
        text = before.decode("utf-8")
        if old == new or text.count(old) != 1:
            raise Unkeyable(f"the edit does not apply exactly once: {fields[0]}")
        after = text.replace(old, new).encode("utf-8")
        if SORRY.search(after.decode("utf-8")):
            raise Unkeyable(f"the mutated file contains sorry: {fields[0]}")
        parts += ["text", fields[1], before, after,
                  closure_digest(tree.with_overlay({fields[1]: after}), roots)]
    return digest(*parts)


def control_key(tree: Tree, base: str, goal: str, api: dict) -> str:
    """The key of a goal's control replay: the base, the goal, the function and its source file,
    the registry of theorems, and every Lean source of the library. The replay picks the registered
    proof from the whole compiled library, so the whole library is hashed, not a closure."""
    registry = tree.read("tests/audit/theorems.txt")
    if registry is None:
        raise Unkeyable("missing tests/audit/theorems.txt")
    return digest("control", base, goal, api["function"], api["source"], registry, tree.library_digest_once())


def replay_key(tree: Tree, base: str, goal: str, api: dict, list_path: str, line: str) -> str:
    """The key of one keyed row's replay against one goal: everything of the control key, the row,
    and the source file after the edit."""
    fields = row_fields(line)
    before = tree.read(api["source"])
    if before is None or len(fields) < 5:
        raise Unkeyable(f"missing source or malformed row for {goal}")
    old, new = fields[2].replace("\\n", "\n"), fields[3].replace("\\n", "\n")
    text = before.decode("utf-8")
    if old == new or text.count(old) != 1:
        raise Unkeyable(f"the edit does not apply exactly once: {fields[0]}")
    return digest("replay", control_key(tree, base, goal, api), list_path, line,
                  text.replace(old, new).encode("utf-8"))


