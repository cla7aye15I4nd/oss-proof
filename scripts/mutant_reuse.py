#!/usr/bin/env python3
"""Verdict reuse for the proof-mutant stage: content keys and the verdict store.

A unit of the stage is one row of a mutant list (run by tests/audit/proofmut.sh), the control
replay of one keyed goal, or the replay of one keyed row against one goal. Each unit gets a key:
a sha256 over every input that can change its verdict. A pre-check run (`verification.py mutants
--reuse STORE`) skips a unit whose key has a passing verdict in the store. A full run never reads
a store. See docs/checking/proof-mutants.md, section "Verdict reuse".

Rules that keep this from becoming a way around the check:
- the key is derived here and nowhere else;
- a key that cannot be computed (an import this parser does not understand, a mutator that fails,
  a `sorry` in the tree) makes the unit run: it never fails the run and never reuses;
- only a passing verdict of the expected kind is reused; everything else runs again;
- what is hashed errs on the side of too much.

`python3 scripts/mutant_reuse.py merge --out FILE STORE...` merges stores (the workflow's last step).
`python3 scripts/mutant_reuse.py durations --out FILE STORE...` writes the recorded seconds of each
unit, the input of the shard packing.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# Bump when the meaning of a key or of a record changes: every stored verdict is then ignored.
SCHEMA = 1
# The programs that produce a verdict. An edit to any of them changes every key.
TOOLS = ("scripts/verification.py", "scripts/mutant_reuse.py", "scripts/mutation_spans.py",
         "tests/audit/proofmut.sh", "tests/audit/ReplayPublicProof.lean", "tests/audit/DeclarationSpan.lean")
# The build configuration. lake-manifest.json is generated by Lake; it is hashed when present.
CONFIG = ("lean-toolchain", "lakefile.toml", "lake-manifest.json")
# Environment that changes what the runner or the replay does.
ENVIRONMENT = ("PROOFMUT_CACHE", "PROOFMUT_TIMEOUT", "PROOFMUT_BASELINE", "PROOFMUT_KEEP", "PROOFMUT_STRICT",
               "PROOFMUT_SHOWLOG", "ZLIBF_REPLAY_RSS_MB", "ZLIBF_REQUIRE_PREBUILT")
# The passing verdict of each kind of unit. Nothing else is ever stored or reused.
PASSING = {"row": "KILLED", "row-same": "SAME ok", "control": "REPLAYED", "replay": "REJECTED"}
RECORD_FIELDS = {"schema", "key", "kind", "unit", "verdict", "detail", "peak_mb", "seconds",
                 "commit", "run", "repository", "time"}
SORRY = re.compile(r"(?<![A-Za-z0-9_])sorry(?![A-Za-z0-9_])")
MAX_AGE_DAYS = 45


class Unkeyable(Exception):
    """The key of a unit cannot be computed. The unit runs; nothing is reused or recorded for it."""


def digest(*parts) -> str:
    """sha256 over length-prefixed parts, so no two part lists share an encoding."""
    h = hashlib.sha256()
    for part in parts:
        data = part if isinstance(part, bytes) else str(part).encode("utf-8")
        h.update(len(data).to_bytes(8, "big"))
        h.update(data)
    return h.hexdigest()


# ---------------------------------------------------------------------------------------------
# Import closure
# ---------------------------------------------------------------------------------------------

MODIFIERS = {"public", "private", "meta"}


def header_imports(text: str, label: str = "") -> list[str]:
    """The modules a Lean file imports, read from its header.

    The header is `module`, `prelude` and import commands, with white space and comments between
    them. Each import names one module: `[public|private|meta]* import [all] Name`. Anything else
    on the line of an import (a second module name, a command) is not understood and raises
    Unkeyable, so an import this parser would miss cannot hide behind one it reads.
    """
    names = []
    i, n = 0, len(text)

    def skip(i: int, same_line: bool = False) -> int:
        while i < n:
            if text.startswith("--", i):
                end = text.find("\n", i)
                i = n if end < 0 else end
            elif text.startswith("/-", i):
                depth, i = 1, i + 2
                while i < n and depth:
                    if text.startswith("/-", i):
                        depth, i = depth + 1, i + 2
                    elif text.startswith("-/", i):
                        depth, i = depth - 1, i + 2
                    else:
                        i += 1
                if depth:
                    raise Unkeyable(f"unterminated comment in the header of {label}")
            elif text[i] == "\n" and same_line:
                return i
            elif text[i].isspace():
                i += 1
            else:
                return i
        return i

    def token(i: int) -> tuple[str, int]:
        start = i
        while i < n and not text[i].isspace():
            if text[i] == "«":
                end = text.find("»", i)
                if end < 0:
                    raise Unkeyable(f"unterminated «» in the header of {label}")
                i = end + 1
            elif text.startswith("--", i) or text.startswith("/-", i):
                break
            else:
                i += 1
        return text[start:i], i

    while True:
        i = skip(i)
        word, after = token(i)
        if word in ("module", "prelude") and not names:
            i = after
            continue
        if word not in MODIFIERS and word != "import":
            return names
        while word in MODIFIERS:
            word, after = token(skip(after))
        if word != "import":
            raise Unkeyable(f"import modifier without an import in {label}")
        name, after = token(skip(after))
        if name == "all":
            name, after = token(skip(after))
        if not name or name in MODIFIERS or name in ("import", "all") or not re.fullmatch(
                r"(?:«[^»\n]+»|[^.\s«»]+)(?:\.(?:«[^»\n]+»|[^.\s«»]+))*", name):
            raise Unkeyable(f"import without a module name in {label}: {name!r}")
        names.append(name)
        # The rest of the line: nothing, a comment, or the next import command.
        rest = skip(after, same_line=True)
        if rest < n and text[rest] != "\n":
            following, _ = token(rest)
            if following not in MODIFIERS and following != "import":
                raise Unkeyable(f"text after an import in {label}: {following!r}")
        i = rest


def module_path(name: str) -> str:
    return "/".join(p.strip("«»") for p in re.findall(r"«[^»]+»|[^.]+", name)) + ".lean"


def import_closure(tree: "Tree", roots: list[str]) -> list[tuple[str, str]]:
    """Every source file reachable from `roots` (paths relative to the workspace) by imports, with
    the sha256 of its bytes, sorted; then one ("import:<name>", "") entry for each imported module
    that has no source in the workspace (the toolchain's Init, Std and Lean).

    A root without a source, or a ZlibF module without a source, raises Unkeyable.
    """
    files: dict[str, str] = {}
    outside: set[str] = set()
    todo = list(roots)
    for root in roots:
        if tree.entry(root) is None:
            raise Unkeyable(f"no source for {root}")
    while todo:
        path = todo.pop()
        if path in files:
            continue
        files[path], names = tree.entry(path)
        for name in names:
            child = module_path(name)
            if tree.entry(child) is not None:
                todo.append(child)
            elif name == "ZlibF" or name.startswith("ZlibF."):
                raise Unkeyable(f"import has no source: {name} in {path}")
            else:
                outside.add(name)
    return sorted(files.items()) + [("import:" + name, "") for name in sorted(outside)]


def closure_digest(tree: "Tree", roots: list[str]) -> str:
    return digest("closure", *(x for pair in import_closure(tree, roots) for x in pair))


