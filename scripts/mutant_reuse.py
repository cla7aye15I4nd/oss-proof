class Tree:
    """Bytes of ordinary files under a root, read once. A symlink is not an input: Unkeyable."""

    def __init__(self, root: Path, overlay: dict[str, bytes] | None = None):
        self.root = Path(root)
        self.overlay = overlay or {}
        self.cache: dict[str, bytes | None] = {}
        self.entries: dict[str, tuple[str, list[str]] | None] = {}
        self.overlay_entries: dict[str, tuple[str, list[str]] | None] = {}

    def read(self, path: str) -> bytes | None:
        if path in self.overlay:
            return self.overlay[path]
        if path not in self.cache:
            p = self.root / path
            relative = Path(path)
            if relative.is_absolute() or ".." in relative.parts:
                raise Unkeyable(f"path leaves the workspace: {path}")
            if p.is_symlink():
                raise Unkeyable(f"symlink among the inputs: {path}")
            self.cache[path] = p.read_bytes() if p.is_file() else None
        return self.cache[path]

    def entry(self, path: str) -> tuple[str, list[str]] | None:
        """(sha256 of the file, the modules its header imports), or None when there is no file."""
        memo = self.overlay_entries if path in self.overlay else self.entries
        if path not in memo:
            data = self.read(path)
            if data is None:
                memo[path] = None
            else:
                try:
                    text = data.decode("utf-8")
                except UnicodeDecodeError:
                    raise Unkeyable(f"{path} is not UTF-8")
                memo[path] = (hashlib.sha256(data).hexdigest(), header_imports(text, path))
        return memo[path]

    def with_overlay(self, overlay: dict[str, bytes]) -> "Tree":
        """The same tree with some files replaced; unreplaced files share this tree's memo."""
        other = Tree(self.root, overlay)
        other.cache = self.cache
        other.entries = self.entries
        return other

    def lean_sources(self) -> list[str]:
        """ZlibF.lean and every .lean file under ZlibF/, sorted."""
        found = ["ZlibF.lean"] if (self.root / "ZlibF.lean").is_file() else []
        for p in sorted((self.root / "ZlibF").rglob("*.lean")):
            found.append(p.relative_to(self.root).as_posix())
        return sorted(found)

    def library_digest(self) -> str:
        """Every Lean source of the library, not only an import closure."""
        parts = []
        for path in self.lean_sources():
            data = self.read(path)
            if data is None:
                raise Unkeyable(f"not an ordinary file: {path}")
            parts += [path, hashlib.sha256(data).hexdigest()]
        if not parts:
            raise Unkeyable("no Lean sources")
        return digest("library", *parts)

    def library_digest_once(self) -> str:
        if not hasattr(self, "_library"):
            self._library = self.library_digest()
        return self._library

    def has_sorry(self) -> bool:
        """The word `sorry` anywhere in the Lean sources, comments included. The list runner fails a
        mutated copy that contains `sorry` outside a comment; that scan reads the whole tree, so a
        tree with the word anywhere gets no reuse at all."""
        for path in self.lean_sources():
            data = self.read(path)
            if data is None or SORRY.search(data.decode("utf-8", "replace")):
                return True
        return False


def base_digest(tree: Tree, tools_root: Path) -> str:
    """What every key shares: this schema, the tools, the build configuration, the platform and the
    environment the runner reads."""
    parts = ["base", SCHEMA]
    for path in TOOLS:
        p = Path(tools_root) / path
        if p.is_symlink() or not p.is_file():
            raise Unkeyable(f"missing tool: {path}")
        parts += [path, hashlib.sha256(p.read_bytes()).hexdigest()]
    for path in CONFIG:
        data = tree.read(path)
        parts += [path, "absent" if data is None else hashlib.sha256(data).hexdigest()]
    parts += [platform.system(), platform.machine()]
    for name in ENVIRONMENT:
        parts += [name, os.environ.get(name, "\0unset")]
    return digest(*parts)


