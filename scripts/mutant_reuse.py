def valid_record(record) -> bool:
    return isinstance(record, dict) and set(record) == RECORD_FIELDS and record["schema"] == SCHEMA and \
        isinstance(record["key"], str) and re.fullmatch(r"[0-9a-f]{64}", record["key"]) is not None and \
        record["kind"] in PASSING and record["verdict"] == PASSING[record["kind"]] and \
        all(isinstance(record[k], str) for k in ("unit", "detail", "commit", "run", "repository", "time")) and \
        all(isinstance(record[k], (int, float)) and not isinstance(record[k], bool) for k in ("peak_mb", "seconds"))


def load_store(path: Path) -> dict[str, dict]:
    """The valid records of a store file by key. A missing or malformed file is an empty store: the
    run then executes everything. An invalid record is dropped, never repaired."""
    try:
        data = json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict) or data.get("version") != SCHEMA or not isinstance(data.get("records"), list):
        return {}
    records: dict[str, dict] = {}
    for record in data["records"]:
        if valid_record(record):
            current = records.get(record["key"])
            if current is None or record["time"] > current["time"]:
                records[record["key"]] = record
    return records


def save_store(path: Path, records: dict[str, dict]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps({"version": SCHEMA, "records": [records[k] for k in sorted(records)]},
                                    indent=1, sort_keys=True) + "\n")
    os.replace(temporary, path)


def now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class Session:
    """One run of the mutants stage that records verdicts and, in a pre-check, reuses them.

    `reuse` is the store to read (None in a full run: nothing is read, whatever exists). `record`
    is the file to write: every unit that passed in this run, and every record this run reused.
    """

    def __init__(self, root: Path, tools_root: Path, reuse: Path | None, record: Path | None):
        self.tree = Tree(root)
        self.record_path = record
        self.reusing = reuse is not None
        self.known = load_store(reuse) if reuse is not None else {}
        self.out: dict[str, dict] = {}
        self.ran = 0
        self.reused = 0
        self.repository = os.environ.get("GITHUB_REPOSITORY", "")
        run_id = os.environ.get("GITHUB_RUN_ID", "")
        self.run = f"{run_id}/{os.environ.get('GITHUB_RUN_ATTEMPT', '1')}" if run_id else "local"
        self.commit = self.head(root)
        self.rows_reusable = True
        try:
            self.base = base_digest(self.tree, tools_root)
            if self.tree.has_sorry():
                self.rows_reusable = False
                print("verdict reuse: the Lean sources contain the word sorry; no list row is reused or recorded")
        except (Unkeyable, OSError) as error:
            self.base = None
            print(f"verdict reuse: no key can be computed ({error}); every unit runs")
        if self.reusing:
            print(f"verdict reuse: {len(self.known)} stored verdicts read; this is a pre-check, not an acceptance run")
        self.save()

    @staticmethod
    def head(root: Path) -> str:
        try:
            commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, text=True,
                                             stderr=subprocess.DEVNULL).strip()
            dirty = subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], cwd=root,
                                            text=True, stderr=subprocess.DEVNULL).strip()
            return commit + ("+dirty" if dirty else "")
        except (OSError, subprocess.CalledProcessError):
            return "unknown"

    def key(self, compute) -> str | None:
        """A key, or None when it cannot be computed. Never raises: an unkeyable unit simply runs."""
        if self.base is None:
            return None
        try:
            return compute()
        except (Unkeyable, OSError, ValueError, KeyError, IndexError) as error:
            print(f"verdict reuse: no key ({error})")
            return None

    def row(self, list_path: str, line: str) -> str | None:
        if not self.rows_reusable:
            return None
        return self.key(lambda: row_key(self.tree, self.base, list_path, line))

    def control(self, goal: str, api: dict) -> str | None:
        return self.key(lambda: control_key(self.tree, self.base, goal, api))

    def replay(self, goal: str, api: dict, list_path: str, line: str) -> str | None:
        return self.key(lambda: replay_key(self.tree, self.base, goal, api, list_path, line))

    def lookup(self, key: str | None, kind: str, unit: str) -> bool:
        """True when the unit's verdict is reused. Prints the unit's REUSED line; the caller prints
        nothing more and does not run it."""
        if not self.reusing or key is None:
            return False
        record = self.known.get(key)
        if record is None or not valid_record(record) or record["key"] != key or record["kind"] != kind or \
                record["verdict"] != PASSING[kind] or record["repository"] != self.repository:
            return False
        self.reused += 1
        self.out[key] = record
        self.save()
        print(f"REUSED {key[:12]} from {record['commit'][:12]} (run {record['run']}) {unit}", flush=True)
        return True

    def passed(self, key: str | None, kind: str, unit: str, *, detail: str = "", peak: int = 0,
               seconds: float = 0) -> None:
        """Record a unit that ran in this run and passed with the verdict of its kind."""
        self.ran += 1
        print(f"RAN {key[:12] if key else 'no key':12} {unit}", flush=True)
        if key is None:
            return
        self.out[key] = {"schema": SCHEMA, "key": key, "kind": kind, "unit": unit, "verdict": PASSING[kind],
                         "detail": detail[:300], "peak_mb": peak >> 20, "seconds": round(seconds, 1),
                         "commit": self.commit, "run": self.run, "repository": self.repository, "time": now()}
        self.save()

    def save(self) -> None:
        if self.record_path is not None:
            save_store(self.record_path, self.out)

    # -- list rows ---------------------------------------------------------------------------

    def pending_rows(self, list_path: str, rows: list[str]) -> tuple[list[str], dict[str, str | None]]:
        """The rows of one list that this run executes, in list order, and the key of each.

        The list runner in strict mode needs a killed row in every list it runs. So when only
        `same:` rows are left to run, the first killable row of the list runs again beside them.
        """
        keys = {line: self.row(list_path, line) for line in rows}
        pending = [line for line in rows
                   if not self.lookup(keys[line], row_kind(line), f"row {list_path}: {row_fields(line)[0]}")]
        if pending and all(row_kind(line) == "row-same" for line in pending):
            again = next((line for line in rows if row_kind(line) == "row"), None)
            if again is not None:
                self.reused -= 1
                self.out.pop(keys[again], None)
                self.save()
                print(f"verdict reuse: {list_path}: {row_fields(again)[0]} runs again beside the same: rows")
                pending = [line for line in rows if line in pending or line == again]
        return pending, keys

    def record_rows(self, list_path: str, pending: list[str], keys: dict[str, str | None], verdicts: Path) -> None:
        """Record the rows of a list run that passed as a whole. `verdicts` is the file the runner
        wrote: one `name<TAB>verdict<TAB>seconds<TAB>detail` line per row, in the order run. Any
        mismatch with the rows asked for records nothing."""
        try:
            lines = [line.split("\t") for line in Path(verdicts).read_text().split("\n") if line]
        except OSError:
            lines = []
        names = [row_fields(line)[0] for line in pending]
        matches = len(lines) == len(pending) and all(len(f) >= 3 for f in lines) and [f[0] for f in lines] == names
        for position, line in enumerate(pending):
            unit = f"row {list_path}: {names[position]}"
            kind = row_kind(line)
            if not matches or lines[position][1] != PASSING[kind] or not lines[position][2].isdigit():
                self.passed(None, kind, unit)
                continue
            self.passed(keys[line], kind, unit, detail=lines[position][3] if len(lines[position]) > 3 else "",
                        seconds=int(lines[position][2]))

    def summary(self) -> str:
        total = self.ran + self.reused
        if self.reusing:
            return (f"mutants: {total} units, {self.ran} ran, {self.reused} reused "
                    "(pre-check with reused verdicts; an accepted result needs a full run)")
        return f"mutants: {total} units, {self.ran} ran, 0 reused (full run)"


# ---------------------------------------------------------------------------------------------
# Merging stores (the workflow's last step)
# ---------------------------------------------------------------------------------------------

def merge(paths: list[Path], max_age_days: int = MAX_AGE_DAYS) -> dict[str, dict]:
    """The union of the valid records of several stores; the newest record of a key wins; a record
    older than the limit is dropped."""
    limit = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=max_age_days)
             ).strftime("%Y-%m-%dT%H:%M:%SZ")
    merged: dict[str, dict] = {}
    for path in paths:
        for key, record in load_store(path).items():
            if record["time"] >= limit and (key not in merged or record["time"] > merged[key]["time"]):
                merged[key] = record
    return merged


def durations(paths: list[Path]) -> dict[str, float]:
    """The seconds of every unit the stores record (the newest record of a unit wins): the input of
    the shard packing, tests/proof-mutants/durations.json."""
    newest: dict[str, dict] = {}
    for path in paths:
        for record in load_store(path).values():
            if record["unit"] not in newest or record["time"] > newest[record["unit"]]["time"]:
                newest[record["unit"]] = record
    return {unit: newest[unit]["seconds"] for unit in sorted(newest)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("merge", "durations"))
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--run", help="merge: the run whose own verdicts are counted apart (ID/ATTEMPT)")
    parser.add_argument("stores", type=Path, nargs="*")
    args = parser.parse_intermixed_args()
    if args.mode == "durations":
        seconds = durations(args.stores)
        args.out.write_text(json.dumps({"version": 1, "seconds": seconds}, indent=1, sort_keys=True) + "\n")
        print(f"durations of {len(seconds)} units")
        return 0
    merged = merge(args.stores)
    save_store(args.out, merged)
    own = sum(1 for record in merged.values() if record["run"] == args.run)
    print(f"verdict store: {len(merged)} verdicts" +
          (f", {own} produced by this run ({args.run}), {len(merged) - own} from earlier runs" if args.run else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
